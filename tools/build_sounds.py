#!/usr/bin/env python3
"""Converts the chosen CC0 clips to mono Ogg Vorbis, writes sounds.json, ModSounds.java, subtitles and CREDITS.
Usage: python3 tools/build_sounds.py"""
import json, os, subprocess, sys, glob, re
sys.path.insert(0, os.path.dirname(__file__))
from sound_map import RAW, MOBS, EXTRA
HOME = os.path.expanduser("~/Projets/Minecraft-QuantumRift/sound-dl/raw")
ROOT = os.path.join(os.path.dirname(__file__), "..")
RES = os.path.join(ROOT, "common/src/main/resources/assets/quantumrift")
JAVA = os.path.join(ROOT, "common/src/main/java/com/quantumrift/content/ModSounds.java")
MOD = "quantumrift"

def find(src):
    key, name = src.split("/", 1)
    d = os.path.join(HOME, RAW[key])
    if os.path.isfile(d): return d
    hits = [p for p in glob.glob(os.path.join(d, "**", name), recursive=True) if not os.path.basename(p).startswith("._")]
    assert hits, f"missing {src}"
    return hits[0]

def convert(src, out, trim=None):
    os.makedirs(os.path.dirname(out), exist_ok=True)
    f = find(src)
    cmd = ["ffmpeg", "-y", "-v", "error", "-i", f]
    if trim: cmd += ["-t", str(trim)]
    cmd += ["-ac", "1", "-ar", "44100", "-af", "silenceremove=start_periods=1:start_threshold=-50dB,loudnorm=I=-20:TP=-3:LRA=7",
            "-ar", "44100", "-c:a", "libvorbis", "-q:a", "4", out]
    subprocess.run(cmd, check=True)
    return f

def main():
    sounds, events = {}, []
    def add(event, spec, folder):
        src, pitch, vol, *tr = spec
        rel = f"{folder}/{event.replace('.', '_')}"
        f = convert(src, os.path.join(RES, "sounds", rel + ".ogg"), tr[0] if tr else None)
        sounds[event] = {"sounds": [{"name": f"{MOD}:{rel}", "pitch": pitch, "volume": vol}], "subtitle": f"subtitles.{MOD}.{event}"}
        events.append(event)
    for mob, trio in MOBS.items():
        for kind, spec in zip(("ambient", "hurt", "death"), trio): add(f"mob.{mob}.{kind}", spec, "mob")
    for ev, spec in EXTRA.items(): add(ev, spec, "misc")
    json.dump(sounds, open(os.path.join(RES, "sounds.json"), "w"), indent=2)
    # Java constants
    def const(e): return e.upper().replace(".", "_")
    lines = ["package com.quantumrift.content;", "", "import com.quantumrift.Constants;", "import com.quantumrift.registry.Registrar;",
             "import net.minecraft.core.registries.BuiltInRegistries;", "import net.minecraft.resources.ResourceLocation;", "import net.minecraft.sounds.SoundEvent;", "",
             "import java.util.function.Supplier;", "", "/** GENERATED by tools/build_sounds.py - do not edit. */", "public final class ModSounds {", ""]
    for e in events:
        lines.append(f'    public static final Supplier<SoundEvent> {const(e)} = reg("{e}");')
    lines += ["", "    private ModSounds() {}", "",
              "    private static Supplier<SoundEvent> reg(String name) {",
              "        return Registrar.register(BuiltInRegistries.SOUND_EVENT, name,",
              "                () -> SoundEvent.createVariableRangeEvent(ResourceLocation.fromNamespaceAndPath(Constants.MOD_ID, name)));",
              "    }", "", "    public static void init() {}", "}", ""]
    open(JAVA, "w").write("\n".join(lines))
    # subtitles into lang
    for lang in ("en_us", "fr_fr"):
        p = os.path.join(RES, f"lang/{lang}.json"); d = json.load(open(p)) if os.path.exists(p) else {}
        for e in events:
            d[f"subtitles.{MOD}.{e}"] = e.replace("mob.", "").replace(".", " ").replace("_", " ").title() if lang == "en_us" else e.replace("mob.", "").replace(".", " ").replace("_", " ")
        json.dump(d, open(p, "w"), indent=2, ensure_ascii=False)
    print(len(events), "events;", sum(os.path.getsize(p) for p in glob.glob(RES + "/sounds/**/*.ogg", recursive=True)) // 1024, "KB of audio")

if __name__ == "__main__":
    main()
