#!/usr/bin/env python3
"""Generates the mob Java sources from tools/mob_table.py: entity classes, ModEntities, ClientRenderers, ModEggs."""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from mob_table import MOBS
J = os.path.join(os.path.dirname(__file__), "..", "common/src/main/java/com/quantumrift")
HAS_BOSS = os.path.exists(os.path.join(J, "entity/VoidSovereign.java"))
mobs = {k: v for k, v in MOBS.items() if HAS_BOSS or not v.get("boss")}
const = lambda mid: mid.upper()
MOB_PRED = lambda m: m.get("parent") in ("IronGolem", "Phantom") or m["cls"] == "VoidJelly"
FIRE_IMMUNE = {"ion_wisp", "ashen_revenant", "void_sovereign"}

def write(rel, text):
    p = os.path.join(J, rel); os.makedirs(os.path.dirname(p), exist_ok=True); open(p, "w").write(text)

def entity_class(mid, m):
    parent, pkg, cls = m["parent"], m["pkg"], m["cls"]
    attrs = m["attrs"]; extra = m.get("extra", "")
    s = f"""package com.quantumrift.entity;

import com.quantumrift.content.ModSounds;
import net.minecraft.sounds.SoundEvent;
import net.minecraft.world.damagesource.DamageSource;
import net.minecraft.world.effect.MobEffectInstance;
import net.minecraft.world.effect.MobEffects;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.entity.EntityType;
import net.minecraft.world.entity.LivingEntity;
import net.minecraft.world.entity.ai.attributes.AttributeSupplier;
import net.minecraft.world.entity.ai.attributes.Attributes;
import net.minecraft.world.entity.monster.*;
import net.minecraft.world.entity.animal.IronGolem;
import net.minecraft.world.level.Level;

/** GENERATED by tools/gen_mobs.py from tools/mob_table.py - do not edit. */
public class {cls} extends {parent} {{

    public {cls}(EntityType<? extends {parent}> type, Level level) {{
        super(type, level);
    }}

    public static AttributeSupplier.Builder createAttributes() {{
        return {attrs};
    }}
{extra}
"""
    if parent not in ("Creeper", "IronGolem"):
        s += f"    @Override\n    protected SoundEvent getAmbientSound() {{\n        return ModSounds.MOB_{const(mid)}_AMBIENT.get();\n    }}\n\n"
    s += f"""    @Override
    protected SoundEvent getHurtSound(DamageSource source) {{
        return ModSounds.MOB_{const(mid)}_HURT.get();
    }}

    @Override
    protected SoundEvent getDeathSound() {{
        return ModSounds.MOB_{const(mid)}_DEATH.get();
    }}
}}
"""
    write(f"entity/{cls}.java", s)

def mod_entities():
    s = """package com.quantumrift.entity;

import com.quantumrift.registry.Registrar;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.entity.EntityType;
import net.minecraft.world.entity.LivingEntity;
import net.minecraft.world.entity.Mob;
import net.minecraft.world.entity.MobCategory;
import net.minecraft.world.entity.SpawnPlacementType;
import net.minecraft.world.entity.SpawnPlacementTypes;
import net.minecraft.world.entity.SpawnPlacements;
import net.minecraft.world.entity.ai.attributes.AttributeSupplier;
import net.minecraft.world.entity.monster.Monster;
import net.minecraft.world.level.levelgen.Heightmap;

import java.util.function.BiConsumer;
import java.util.function.Supplier;

/** GENERATED by tools/gen_mobs.py from tools/mob_table.py - do not edit. */
public final class ModEntities {

"""
    for mid, m in mobs.items():
        w, h = m["size"]; fi = ".fireImmune()" if mid in FIRE_IMMUNE else ""
        track = 10 if m.get("boss") or m["cls"] == "VoidJelly" else 8
        extra = ".spawnDimensionsScale(4.0F)" if m["cls"] == "VoidJelly" else ""
        s += f'    public static final Supplier<EntityType<{m["cls"]}>> {const(mid)} = reg("{mid}", () ->\n            EntityType.Builder.<{m["cls"]}>of({m["cls"]}::new, MobCategory.MONSTER).sized({w}F, {h}F){extra}{fi}.clientTrackingRange({track}).build("quantumrift:{mid}"));\n'
    s += """
    private ModEntities() {}

    @SuppressWarnings("unchecked")
    private static <T extends Entity> Supplier<EntityType<T>> reg(String name, Supplier<EntityType<T>> factory) {
        Supplier<EntityType<?>> s = Registrar.register(BuiltInRegistries.ENTITY_TYPE, name, factory);
        return () -> (EntityType<T>) s.get();
    }

    public static void init() {}

    /** Called by each loader from its attribute-creation hook. */
    public static void attributes(BiConsumer<EntityType<? extends LivingEntity>, AttributeSupplier> out) {
"""
    for mid, m in mobs.items():
        s += f'        out.accept({const(mid)}.get(), {m["cls"]}.createAttributes().build());\n'
    s += """    }

    public interface PlacementRegistrar {
        <T extends Mob> void register(EntityType<T> type, SpawnPlacementType placement, Heightmap.Types heightmap, SpawnPlacements.SpawnPredicate<T> predicate);
    }

    /** Called by each loader from its spawn-placement hook. */
    public static void placements(PlacementRegistrar r) {
"""
    for mid, m in mobs.items():
        place = "NO_RESTRICTIONS" if m["spawn"] == "air" else "ON_GROUND"
        if MOB_PRED(m):
            pred = "(type, level, reason, pos, random) -> level.getDifficulty() != net.minecraft.world.Difficulty.PEACEFUL\n                        && Monster.isDarkEnoughToSpawn(level, pos, random) && Mob.checkMobSpawnRules(type, level, reason, pos, random)"
        else:
            pred = "Monster::checkMonsterSpawnRules"
        s += f"        r.register({const(mid)}.get(), SpawnPlacementTypes.{place}, Heightmap.Types.MOTION_BLOCKING_NO_LEAVES,\n                {pred});\n"
    s += "    }\n}\n"
    write("entity/ModEntities.java", s)

PARAM = {"VexRenderer": "Vex", "EndermanRenderer": "EnderMan", "SpiderRenderer": "Spider", "SlimeRenderer": "Slime", "RavagerRenderer": "Ravager", "IronGolemRenderer": "IronGolem",
         "PhantomRenderer": "Phantom", "BlazeRenderer": "Blaze", "CreeperRenderer": "Creeper", "EndermiteRenderer": "Endermite", "ZombieRenderer": "Zombie", "SkeletonRenderer": "AbstractSkeleton",
         "WitherSkeletonRenderer": "WitherSkeleton", "SilverfishRenderer": "Silverfish", "WitchRenderer": "Witch", "PillagerRenderer": "Pillager"}
def renderers():
    s = """package com.quantumrift.client;

import com.mojang.blaze3d.vertex.PoseStack;
import com.quantumrift.Constants;
import com.quantumrift.entity.*;
import net.minecraft.client.model.SkeletonModel;
import net.minecraft.client.model.geom.ModelLayers;
import net.minecraft.client.renderer.entity.*;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.entity.EntityType;
import net.minecraft.world.entity.animal.IronGolem;
import net.minecraft.world.entity.monster.*;

/** GENERATED by tools/gen_mobs.py from tools/mob_table.py - do not edit. Vanilla models with our own textures. */
public final class ClientRenderers {

    public interface Sink {
        <T extends Entity> void register(EntityType<? extends T> type, EntityRendererProvider<T> provider);
"""
    s += """    }

    public interface LayerSink {
        void register(net.minecraft.client.model.geom.ModelLayerLocation layer, java.util.function.Supplier<net.minecraft.client.model.geom.builders.LayerDefinition> definition);
    }

    private ClientRenderers() {}

    private static ResourceLocation tex(String path) {
        return ResourceLocation.fromNamespaceAndPath(Constants.MOD_ID, "textures/entity/" + path + ".png");
    }

    public static void register(Sink sink) {
"""
    for mid, m in mobs.items():
        if m.get("boss"):
            s += f"        sink.register(ModEntities.{const(mid)}.get(), VoidSovereignRenderer::new);\n"; continue
        r = m["renderer"]; c = const(mid)
        if r == "VexRenderer":
            s += f'        sink.register(ModEntities.{c}.get(), ctx -> new VexRenderer(ctx) {{\n            @Override\n            public ResourceLocation getTextureLocation(Vex e) {{\n                return e.isCharging() ? tex("phase_wraith_charging") : tex("phase_wraith");\n            }}\n        }});\n'; continue
        if r == "HumanoidMobRenderer":
            s += f'        sink.register(ModEntities.{c}.get(), ctx -> new HumanoidMobRenderer<GauntWatcher, SkeletonModel<GauntWatcher>>(ctx, new SkeletonModel<>(ctx.bakeLayer(ModelLayers.SKELETON)), 0.5F) {{\n            @Override\n            public ResourceLocation getTextureLocation(GauntWatcher e) {{\n                return tex("{mid}");\n            }}\n        }});\n'; continue
        p = PARAM[r]; gen = "<Spider>" if r == "SpiderRenderer" else ""
        scale = ""
        if m.get("scale"):
            k = m["scale"]; scale = f"\n            @Override\n            protected void scale({p} e, PoseStack poseStack, float partialTick) {{\n                poseStack.scale({k}F, {k}F, {k}F);\n            }}\n"
        s += f'        sink.register(ModEntities.{c}.get(), ctx -> new {r}{gen}(ctx) {{\n            @Override\n            public ResourceLocation getTextureLocation({p} e) {{\n                return tex("{mid}");\n            }}\n{scale}        }});\n'
    s += "    }\n\n    public static void registerLayers(LayerSink sink) {\n"
    if HAS_BOSS: s += "        sink.register(VoidSovereignModel.LAYER, VoidSovereignModel::createBodyLayer);\n"
    s += "    }\n}\n"
    write("client/ClientRenderers.java", s)

def eggs():
    s = """package com.quantumrift.content;

import com.quantumrift.entity.ModEntities;
import net.minecraft.world.item.Item;

import java.util.function.Supplier;

/** GENERATED by tools/gen_mobs.py from tools/mob_table.py - do not edit. */
public final class ModEggs {

"""
    for mid in mobs:
        s += f'    public static final Supplier<Item> {const(mid)}_SPAWN_EGG = ModItems.item("{mid}_spawn_egg", () -> new QRSpawnEggItem(ModEntities.{const(mid)}, new Item.Properties()));\n'
    s += "\n    private ModEggs() {}\n\n    public static void init() {}\n}\n"
    write("content/ModEggs.java", s)

if __name__ == "__main__":
    for mid, m in mobs.items():
        if m.get("gen", True): entity_class(mid, m)
    mod_entities(); renderers(); eggs()
    print(len(mobs), "mobs (boss class", "present" if HAS_BOSS else "absent", ")")
