def nbt_str(s): b = s.encode(); return struct.pack(">H", len(b)) + b
def tag(t, name, payload): return bytes([t]) + nbt_str(name) + payload
def n_int(v): return struct.pack(">i", v)
def n_list(tid, items): return bytes([tid]) + struct.pack(">i", len(items)) + b"".join(items)
def n_comp(entries): return b"".join(entries) + b"\x00"

def structure_nbt():
    X, Y, Z_ = 11, 9, 11
    cells = {}
    def put(x, y, z, name, props=None): cells[(x, y, z)] = (name, props or {})
    for x in range(X):
        for z in range(Z_):
            edge = x in (0, X - 1) or z in (0, Z_ - 1)
            put(x, 0, z, "minecraft:chiseled_polished_blackstone" if edge else ("minecraft:cracked_polished_blackstone_bricks" if (x * 7 + z * 3) % 5 == 0 else "minecraft:polished_blackstone_bricks"))
    for cx, cz in ((0, 0), (X - 1, 0), (0, Z_ - 1), (X - 1, Z_ - 1)):   # corner pillars
        for y in range(1, 5): put(cx, y, cz, "minecraft:polished_blackstone")
        put(cx, 5, cz, "minecraft:sea_lantern")
    zf = 6                                                              # the gate plane
    for x in range(3, 9):
        for y in range(1, 9):
            border = x in (3, 8) or y in (1, 8)
            if border:
                put(x, y, zf, "minecraft:crying_obsidian" if (x in (3, 8) and y in (1, 8)) else f"{MOD}:quantite_block")
            else:
                put(x, y, zf, f"{MOD}:dormant_rift")
    put(5, 1, 3, f"{MOD}:rift_gate_core", {"rods": "0"})                # socket in front of the gate
    for dx in (-1, 1): put(5 + dx, 1, 3, "minecraft:polished_blackstone_stairs", {"facing": "east" if dx < 0 else "west", "half": "bottom", "shape": "straight", "waterlogged": "false"})
    palette, index = [], {}
    for (name, props) in cells.values():
        k = (name, tuple(sorted(props.items())))
        if k not in index: index[k] = len(palette); palette.append(k)
    blocks = [n_comp([tag(9, "pos", n_list(3, [n_int(x), n_int(y), n_int(z)])), tag(3, "state", n_int(index[(n, tuple(sorted(p.items())))]))])
              for (x, y, z), (n, p) in sorted(cells.items(), key=lambda kv: (kv[0][1], kv[0][2], kv[0][0]))]
    pal = []
    for name, props in palette:
        e = [tag(8, "Name", nbt_str(name))]
        if props: e.append(tag(10, "Properties", n_comp([tag(8, k, nbt_str(v)) for k, v in props])))
        pal.append(n_comp(e))
    root = tag(10, "", n_comp([tag(9, "size", n_list(3, [n_int(X), n_int(Y), n_int(Z_)])), tag(9, "entities", n_list(0, [])),
                                tag(9, "blocks", n_list(10, blocks)), tag(9, "palette", n_list(10, pal)), tag(3, "DataVersion", n_int(3955))]))
    p = os.path.join(ROOT, f"data/{MOD}/structure/rift_gate.nbt"); os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, "wb").write(gzip.compress(root))

