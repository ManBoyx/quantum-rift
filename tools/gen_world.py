def fused():
    order = feature_order()
    custom = horror_features()
    sets = {  # id: (sources, colours)   -- deliberately drained and sickly
        "fused_frostbloom": (["cherry_grove", "snowy_plains", "ice_spikes", "snowy_taiga"], dict(sky=0x5d6670, fog=0x2b2f38, water=0x2b3a50, grass=0x8a9aa0, foliage=0xa08892)),
        "fused_scorchwild": (["desert", "jungle", "wooded_badlands"], dict(sky=0x6b4a3a, fog=0x3a2418, water=0x35502f, grass=0x8a7a40, foliage=0x4a6a3a)),
        "fused_mirewood": (["swamp", "dark_forest", "mangrove_swamp"], dict(sky=0x4a3f52, fog=0x1f1a24, water=0x2a2f2a, grass=0x4a5a3a, foliage=0x5a4a6a))}
    for name, (srcs, col) in sets.items():
        bs = [vjson(f"worldgen/biome/{s}.json") for s in srcs]
        feats = [[] for _ in range(11)]
        for b in bs:
            for step, lst in enumerate(b["features"]):
                for f in lst:
                    if any(k in f for k in CHEERFUL): continue
                    if f not in feats[step]: feats[step].append(f)
        for step in range(11): feats[step].sort(key=lambda f: order[step][f])
        for step, extra in custom.items(): feats[step] += extra          # our own features go last (after the globally ordered vanilla ones)
        sp = {k: [] for k in bs[0]["spawners"]}                          # no animals here: the land is dead
        sp["monster"] = spawn_entries(HORROR_SPAWNS)
        carv = []
        for b in bs:
            c = b.get("carvers", {}).get("air", [])
            for x in ([c] if isinstance(c, str) else c):
                if x not in carv: carv.append(x)
        eff = dict(bs[0]["effects"])
        eff.update({"sky_color": col["sky"], "fog_color": col["fog"], "water_color": col["water"], "water_fog_color": col["fog"], "grass_color": col["grass"], "foliage_color": col["foliage"]})
        eff.update(HORROR_SOUNDS)
        eff["particle"] = {"options": {"type": "minecraft:ash"}, "probability": 0.012}
        w(f"data/{MOD}/worldgen/biome/{name}.json", {"temperature": bs[0]["temperature"], "downfall": 0.6, "has_precipitation": bs[0]["has_precipitation"],
            **({"temperature_modifier": bs[0]["temperature_modifier"]} if "temperature_modifier" in bs[0] else {}),
            "effects": eff, "spawners": sp, "spawn_costs": {}, "carvers": {"air": carv}, "features": feats})
        s_all = [f for st in feats for f in st if not f.startswith(MOD + ":")]
        missing = [f for f in s_all if f"data/minecraft/worldgen/placed_feature/{f.split(':')[-1]}.json" not in Z.namelist()]
        assert not missing, missing
    names = [f"{MOD}:{n}" for n in sets]
    w("data/minecraft/tags/worldgen/biome/is_overworld.json", {"replace": False, "values": names})
    w(f"data/{MOD}/tags/worldgen/biome/has_structure/rift_gate.json", {"values": names})


