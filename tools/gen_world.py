def feature_order():
    """Global feature order consistent with every vanilla biome (avoids 'feature order cycle' crashes)."""
    names = [n for n in Z.namelist() if n.startswith("data/minecraft/worldgen/biome/") and n.endswith(".json")]
    order = [dict() for _ in range(11)]
    edges = [dict() for _ in range(11)]
    for n in names:
        for step, lst in enumerate(json.loads(Z.read(n))["features"]):
            for f in lst: edges[step].setdefault(f, set())
            for a, b in zip(lst, lst[1:]): edges[step][a].add(b)
    out = []
    for step in range(11):
        g = edges[step]; indeg = {k: 0 for k in g}
        for a in g:
            for b in g[a]: indeg[b] += 1
        ready = sorted(k for k, v in indeg.items() if v == 0); res = []
        while ready:
            k = ready.pop(0); res.append(k)
            for b in sorted(g[k]):
                indeg[b] -= 1
                if indeg[b] == 0: ready.append(b); ready.sort()
        assert len(res) == len(g), "vanilla feature graph has a cycle?!"
        out.append({f: i for i, f in enumerate(res)})
    return out

